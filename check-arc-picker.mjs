import fs from 'node:fs';
import vm from 'node:vm';
import assert from 'node:assert/strict';
const ctx=vm.createContext({console});
for(const name of ['point','node-axis','node-circle','self-tangent-circles','gap-tangent-circles','three-tangent-circle','constructed-arc','graph-model','arc-picker']) vm.runInContext(fs.readFileSync(name+'.js','utf8'),ctx);
const outer=ctx.makeNode('circle'),group=ctx.makeNode('tangent'),arc=ctx.makeNode('arc');group.sourceId=outer.id;
const state={nodes:[outer,group,arc]};state.evaluation=ctx.evaluateGraph(state.nodes);
const picks=ctx.arcPickCandidates(state,arc.id);
const centers=picks.points.filter(p=>p.point.kind==='center'&&p.point.circle.nodeId===group.id);
assert.equal(centers.length,3);
assert.ok(picks.points.some(p=>p.point.kind==='intersection'));
assert.ok(!picks.circles.some(p=>p.ref.nodeId===arc.id));
Object.assign(arc.arcConfig,{support:'defined',center:centers[1].point,radiusMode:'point',radiusPoint:centers[0].point,bounds:'points',startPoint:centers[0].point,endPoint:centers[2].point});
state.evaluation=ctx.evaluateGraph(state.nodes);assert.equal(state.evaluation.errors.size,0);
assert.ok(state.evaluation.results.get(arc.id)[0].radius>100);
outer.params.nRosy=4;state.evaluation=ctx.evaluateGraph(state.nodes);assert.equal(state.evaluation.errors.size,0);
outer.params.rotation+=33;outer.params.x=50;state.evaluation=ctx.evaluateGraph(state.nodes);assert.equal(state.evaluation.errors.size,0);
outer.params.nRosy=2;state.evaluation=ctx.evaluateGraph(state.nodes);assert.ok(state.evaluation.errors.has(arc.id));
console.log('Passed canvas candidates, exclusions, center/start/end construction, parameter changes and missing member handling.');
